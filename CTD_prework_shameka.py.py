#Enter a student's name and test score, then determine the letter grade based on the score.

student = input("Enter the student's name: ")
test_score = float(input("Enter the student's test score: "))

if test_score >= 90:
    grade = 'A'
elif test_score >= 80 and test_score < 90:
    grade = 'B'
elif test_score >= 70 and test_score < 80:
    grade = 'C'
elif test_score >= 60 and test_score < 70:
    grade = 'D'
else:
    grade = 'F'

if grade == 'A':
  print(f"{student} scored {test_score} and received an {grade} on today's math test.")
else:
  print(f"{student} scored {test_score} and received a {grade} on today's math test.")

